using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using CntlmGUI.Models;

namespace CntlmGUI.Services;

/// <summary>
/// 负责把 GuiSettings 渲染成 cntlm 可读取的 ini 文本，
/// 以及从现有 cntlm.ini 导入初始参数。
/// </summary>
public static class CntlmConfigGenerator
{
    /// <summary>未启用二级代理时写一个不可达的占位 Proxy，让 cntlm 满足“必须有上游”的要求。</summary>
    private const string PlaceholderProxy = "127.0.0.1:9";

    /// <summary>未启用二级代理时的占位 NTLM 哈希，仅用于满足 cntlm 的凭据启动校验。</summary>
    private const string PlaceholderPassNT = "77B9081511704EE852F94227CF48A793";

    public static string Generate(GuiSettings s)
    {
        var sb = new StringBuilder();
        sb.AppendLine("#");
        sb.AppendLine("# Cntlm configuration generated by CntlmGUI");
        sb.AppendLine("# Generated at " + DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss"));
        sb.AppendLine("# Do NOT edit this file directly - edit GUI settings instead.");
        sb.AppendLine("#");
        sb.AppendLine();

        // 未启用对外互联时：Proxy 地址用占位值即可，真实凭据保留不会生效
        // （请求到不了上游）；只有完全没配凭据时才补占位，满足 cntlm 启动校验。
        bool realAuth = s.UseProxy || HasUsableAuth(s);
        if (realAuth)
        {
            AppendAuth(sb, s);
        }
        else
        {
            sb.AppendLine("# 未启用对外互联且未配置凭据：以下为占位值，仅用于满足 cntlm 启动校验");
            sb.AppendLine("Username\t" + (string.IsNullOrWhiteSpace(s.Username) ? "cntlmgui" : s.Username.Trim()));
            if (!string.IsNullOrWhiteSpace(s.Domain))
                sb.AppendLine("Domain\t\t" + s.Domain.Trim());
            if (!string.IsNullOrWhiteSpace(s.Workstation))
                sb.AppendLine("Workstation\t" + s.Workstation.Trim());
            sb.AppendLine("PassNT\t\t" + PlaceholderPassNT);
            sb.AppendLine("Auth\t\tNT");
        }

        sb.AppendLine();
        if (s.UseProxy)
        {
            foreach (var line in TextLines.Split(s.ProxyList))
                sb.AppendLine("Proxy\t\t" + line);
        }
        else
        {
            sb.AppendLine("Proxy\t\t" + PlaceholderProxy);
        }

        sb.AppendLine("Listen\t\t" + (string.IsNullOrWhiteSpace(s.Listen) ? "127.0.0.1:8080" : s.Listen.Trim()));

        var noProxy = TextLines.Split(s.NoProxyList);
        if (noProxy.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("NoProxy\t\t" + string.Join(", ", noProxy));
        }

        // 以下都是二级（对外互联）配置：未启用时一律不写入
        if (s.UseProxy && s.UsePac && !string.IsNullOrWhiteSpace(s.PacFile))
        {
            sb.AppendLine();
            sb.AppendLine("Pac\t\t" + s.PacFile.Trim());
        }

        if (s.UseSocks5 && !string.IsNullOrWhiteSpace(s.Socks5Proxy))
        {
            sb.AppendLine();
            sb.AppendLine("SOCKS5Proxy\t" + s.Socks5Proxy.Trim());
            if (!string.IsNullOrWhiteSpace(s.Socks5User))
                sb.AppendLine("SOCKS5User\t" + s.Socks5User.Trim());
        }

        sb.AppendLine();
        if (s.UseAllow)
        {
            foreach (var line in TextLines.Split(s.AllowList))
                sb.AppendLine("Allow\t\t" + line);
            foreach (var line in TextLines.Split(s.DenyList))
                sb.AppendLine("Deny\t\t" + line);
        }

        if (s.UseTunnel && !string.IsNullOrWhiteSpace(s.TunnelList))
        {
            sb.AppendLine();
            sb.AppendLine("# Tunnel 格式: [saddr:]lport:rhost:rport");
            foreach (var line in TextLines.Split(s.TunnelList))
                sb.AppendLine("Tunnel\t\t" + line);
        }

        if (s.UseHeader && !string.IsNullOrWhiteSpace(s.HeaderList))
        {
            sb.AppendLine();
            sb.AppendLine("# Header 替换格式: HeaderName: value");
            foreach (var line in TextLines.Split(s.HeaderList))
                sb.AppendLine("Header\t\t" + line);
        }

        if (s.UseProxy && s.UseIsaScanner)
        {
            var agents = TextLines.Split(s.IsaScannerAgentList);
            // 没有 agent 规则时不启用插件，避免生成“开了但没规则”的配置
            if (agents.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine("ISAScannerSize\t" + Math.Max(0, s.IsaScannerSize));
                foreach (var line in agents)
                    sb.AppendLine("ISAScannerAgent\t" + line);
            }
        }

        if (s.UseSspi)
        {
            sb.AppendLine();
            sb.AppendLine("SSPI\t\t" + (string.IsNullOrWhiteSpace(s.SspiType) ? "NTLM" : s.SspiType.Trim()));
        }

        if (realAuth && !string.IsNullOrWhiteSpace(s.Auth))
            sb.AppendLine("Auth\t\t" + s.Auth.Trim());

        if (realAuth && !string.IsNullOrWhiteSpace(s.Flags))
        {
            var flag = s.Flags.Trim();
            if (!flag.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
                flag = "0x" + flag;
            sb.AppendLine("Flags\t\t" + flag);
        }

        // Gateway yes 允许局域网内其它机器把本机当作代理使用
        if (s.Gateway)
            sb.AppendLine("Gateway\t\tyes");

        return sb.ToString();
    }

    /// <summary>写真实的上游认证信息（用户名/域/工作站 + 哈希或明文密码）。</summary>
    private static void AppendAuth(StringBuilder sb, GuiSettings s)
    {
        sb.AppendLine("Username\t" + s.Username.Trim());
        if (!string.IsNullOrWhiteSpace(s.Domain))
            sb.AppendLine("Domain\t\t" + s.Domain.Trim());
        if (!string.IsNullOrWhiteSpace(s.Workstation))
            sb.AppendLine("Workstation\t" + s.Workstation.Trim());

        // 优先使用哈希；否则回退到明文密码（危险，会给出提示）
        if (TextLines.AnyNonEmpty(s.PassLM, s.PassNT, s.PassNTLMv2))
        {
            if (!string.IsNullOrWhiteSpace(s.PassLM))
                sb.AppendLine("PassLM\t\t" + s.PassLM.Trim());
            if (!string.IsNullOrWhiteSpace(s.PassNT))
                sb.AppendLine("PassNT\t\t" + s.PassNT.Trim());
            if (!string.IsNullOrWhiteSpace(s.PassNTLMv2))
                sb.AppendLine("PassNTLMv2\t" + s.PassNTLMv2.Trim());
        }
        else if (!string.IsNullOrWhiteSpace(s.Password))
        {
            sb.AppendLine("Password\t\"" + s.Password.Replace("\"", "\\\"") + "\"");
            sb.AppendLine();
            sb.AppendLine("# WARNING: plaintext password written to config. Prefer hashes.");
        }
    }

    /// <summary>未启用上游时，现有凭据是否足以让 cntlm 启动（SSPI 也算）。</summary>
    private static bool HasUsableAuth(GuiSettings s) =>
        !string.IsNullOrWhiteSpace(s.Username) &&
        (s.UseSspi || TextLines.AnyNonEmpty(s.PassLM, s.PassNT, s.PassNTLMv2) ||
         !string.IsNullOrWhiteSpace(s.Password));

    /// <summary>
    /// 解析一个现成的 cntlm.ini，回填到 GuiSettings，供首次使用或“导入模板”。
    /// </summary>
    public static GuiSettings Import(string iniPath)
    {
        var cfg = new GuiSettings();
        if (!File.Exists(iniPath)) return cfg;

        var proxies = new List<string>();
        var noProxyLines = new List<string>();
        var allow = new List<string>();
        var deny = new List<string>();
        var tunnel = new List<string>();
        var headers = new List<string>();
        var isaAgents = new List<string>();

        foreach (var raw in File.ReadAllLines(iniPath, Encoding.UTF8))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line.StartsWith("#") || line.StartsWith(";")) continue;

            int sep = line.IndexOfAny(new[] { '\t', ' ' });
            if (sep <= 0) continue;
            var key = line[..sep].Trim();
            var value = line[sep..].Trim().Trim('"');

            switch (key.ToLowerInvariant())
            {
                case "username": cfg.Username = value; break;
                case "domain": cfg.Domain = value; break;
                case "workstation": cfg.Workstation = value; break;
                case "password": cfg.Password = value; break;
                case "passlm": cfg.PassLM = value; break;
                case "passnt": cfg.PassNT = value; break;
                case "passntlmv2": cfg.PassNTLMv2 = value; break;
                case "auth": cfg.Auth = value; break;
                case "flags": cfg.Flags = value; break;
                case "listen": cfg.Listen = value; break;
                case "gateway": cfg.Gateway = value.Equals("yes", StringComparison.OrdinalIgnoreCase); break;
                case "proxy":
                    // 占位 Proxy 表示“未启用二级代理”，导入时不要变成一条真实代理
                    if (value == PlaceholderProxy) break;
                    proxies.Add(value);
                    cfg.UseProxy = true;
                    break;
                case "noproxy": noProxyLines.Add(value); break;
                case "pac": cfg.PacFile = value; cfg.UsePac = true; break;
                case "socks5proxy": cfg.Socks5Proxy = value; cfg.UseSocks5 = true; break;
                case "socks5user": cfg.Socks5User = value; break;
                case "allow": allow.Add(value); cfg.UseAllow = true; break;
                case "deny": deny.Add(value); cfg.UseAllow = true; break;
                case "tunnel": tunnel.Add(value); cfg.UseTunnel = true; break;
                case "header": headers.Add(value); cfg.UseHeader = true; break;
                case "isascannersize":
                    cfg.UseIsaScanner = int.TryParse(value, out var size) && size >= 0;
                    cfg.IsaScannerSize = size;
                    break;
                case "isascanneragent": isaAgents.Add(value); break;
                case "sspi": cfg.UseSspi = true; cfg.SspiType = value; break;
            }
        }

        cfg.ProxyList = string.Join("\r\n", proxies);
        cfg.AllowList = string.Join("\r\n", allow);
        cfg.DenyList = string.Join("\r\n", deny);
        cfg.TunnelList = string.Join("\r\n", tunnel);
        cfg.HeaderList = string.Join("\r\n", headers);
        cfg.IsaScannerAgentList = string.Join("\r\n", isaAgents);
        cfg.NoProxyList = string.Join(", ", noProxyLines);
        return cfg;
    }
}
