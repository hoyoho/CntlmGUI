using System.Text;
using CntlmGUI.Models;

namespace CntlmGUI.Services;

public static class CntlmConfigGenerator
{
    private static readonly UTF8Encoding Utf8NoBom = new(false);

    public static string Generate(GuiSettings s)
    {
        var sb = new StringBuilder();
        sb.AppendLine("#");
        sb.AppendLine("# Cntlm configuration generated by CntlmGUI");
        sb.AppendLine($"# Generated at {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
        sb.AppendLine("# Do NOT edit this file directly - edit GUI settings instead.");
        sb.AppendLine("#");
        sb.AppendLine();

        var hasHashes = !IsBlank(s.PassLM) || !IsBlank(s.PassNT) || !IsBlank(s.PassNTLMv2);
        var hasUsableAuth = !IsBlank(s.Username) && (s.UseSspi || hasHashes || !string.IsNullOrEmpty(s.Password));
        var realAuth = s.UseProxy || hasUsableAuth;

        if (realAuth) AppendRealAuth(sb, s, hasHashes);
        else AppendPlaceholderAuth(sb, s);
        sb.AppendLine();

        if (s.UseProxy)
        {
            var proxies = TextLines.Split(s.ProxyList);
            if (proxies.Length == 0) sb.AppendLine("Proxy 127.0.0.1:9");
            else foreach (var proxy in proxies) sb.AppendLine("Proxy " + proxy);
        }
        else
        {
            sb.AppendLine("Proxy 127.0.0.1:9");
        }

        sb.AppendLine("Listen " + (IsBlank(s.Listen) ? "127.0.0.1:8080" : s.Listen.Trim()));

        var noProxy = TextLines.JoinComma(s.NoProxyList);
        if (noProxy.Length > 0) sb.AppendLine("NoProxy " + noProxy);

        if (s.UseProxy && s.UsePac && !IsBlank(s.PacFile))
            sb.AppendLine("Pac " + s.PacFile.Trim());

        if (s.UseSocks5 && !IsBlank(s.Socks5Proxy))
        {
            sb.AppendLine("SOCKS5Proxy " + s.Socks5Proxy.Trim());
            if (!IsBlank(s.Socks5User)) sb.AppendLine("SOCKS5User " + s.Socks5User.Trim());
        }

        if (s.UseAllow)
        {
            foreach (var allow in TextLines.Split(s.AllowList)) sb.AppendLine("Allow " + allow);
            foreach (var deny in TextLines.Split(s.DenyList)) sb.AppendLine("Deny " + deny);
        }

        var tunnels = TextLines.Split(s.TunnelList);
        if (s.UseTunnel && tunnels.Length > 0)
        {
            sb.AppendLine("# Tunnel 格式: [saddr:]lport:rhost:rport");
            foreach (var tunnel in tunnels) sb.AppendLine("Tunnel " + tunnel);
        }

        var headers = TextLines.Split(s.HeaderList);
        if (s.UseHeader && headers.Length > 0)
        {
            sb.AppendLine("# Header 替换格式: HeaderName: value");
            foreach (var header in headers) sb.AppendLine("Header " + header);
        }

        if (s.UseProxy && s.UseIsaScanner)
        {
            var agents = TextLines.Split(s.IsaScannerAgentList);
            if (agents.Length > 0)
            {
                sb.AppendLine("ISAScannerSize " + Math.Max(0, s.IsaScannerSize));
                foreach (var agent in agents) sb.AppendLine("ISAScannerAgent " + agent);
            }
        }

        if (s.UseSspi)
            sb.AppendLine("SSPI " + (IsBlank(s.SspiType) ? "NTLM" : s.SspiType.Trim()));

        if (realAuth)
        {
            if (!IsBlank(s.Auth)) sb.AppendLine("Auth " + s.Auth.Trim());
            if (!IsBlank(s.Flags))
            {
                var flags = s.Flags.Trim();
                if (!flags.StartsWith("0x", StringComparison.OrdinalIgnoreCase)) flags = "0x" + flags;
                sb.AppendLine("Flags " + flags);
            }
        }

        if (s.Gateway) sb.AppendLine("Gateway yes");

        return sb.ToString();
    }

    public static void WriteFile(string path, GuiSettings settings)
    {
        var dir = Path.GetDirectoryName(path);
        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
        File.WriteAllText(path, Generate(settings), Utf8NoBom);
    }

    private static void AppendRealAuth(StringBuilder sb, GuiSettings s, bool hasHashes)
    {
        if (!IsBlank(s.Username)) sb.AppendLine("Username " + s.Username.Trim());
        if (!IsBlank(s.Domain)) sb.AppendLine("Domain " + s.Domain.Trim());
        if (!IsBlank(s.Workstation)) sb.AppendLine("Workstation " + s.Workstation.Trim());

        if (hasHashes)
        {
            if (!IsBlank(s.PassLM)) sb.AppendLine("PassLM " + s.PassLM.Trim());
            if (!IsBlank(s.PassNT)) sb.AppendLine("PassNT " + s.PassNT.Trim());
            if (!IsBlank(s.PassNTLMv2)) sb.AppendLine("PassNTLMv2 " + s.PassNTLMv2.Trim());
        }
        else if (!string.IsNullOrEmpty(s.Password))
        {
            sb.AppendLine("Password \"" + s.Password.Replace("\"", "\\\"") + "\"");
            sb.AppendLine();
            sb.AppendLine("# WARNING: plaintext password written to config. Prefer hashes.");
        }
    }

    private static void AppendPlaceholderAuth(StringBuilder sb, GuiSettings s)
    {
        sb.AppendLine("# 未启用对外互联且未配置凭据：以下为占位值，仅用于满足 cntlm 启动校验");
        sb.AppendLine("Username    " + (IsBlank(s.Username) ? "cntlmgui" : s.Username.Trim()));
        if (!IsBlank(s.Domain)) sb.AppendLine("Domain      " + s.Domain.Trim());
        if (!IsBlank(s.Workstation)) sb.AppendLine("Workstation " + s.Workstation.Trim());
        sb.AppendLine("PassNT      77B9081511704EE852F94227CF48A793");
        sb.AppendLine("Auth        NT");
    }

    public static GuiSettings Import(string path)
    {
        var settings = new GuiSettings();
        var proxies = new List<string>();
        var noProxy = new List<string>();
        var allow = new List<string>();
        var deny = new List<string>();
        var tunnels = new List<string>();
        var headers = new List<string>();
        var agents = new List<string>();

        foreach (var raw in File.ReadLines(path))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line.StartsWith("#") || line.StartsWith(";")) continue;

            var sep = line.IndexOfAny(new[] { ' ', '\t' });
            string key, value;
            if (sep < 0)
            {
                key = line;
                value = "";
            }
            else
            {
                key = line[..sep];
                value = line[(sep + 1)..].Trim();
            }

            if (value.Length >= 2 && value.StartsWith('"') && value.EndsWith('"'))
                value = value[1..^1];

            switch (key.ToLowerInvariant())
            {
                case "username":
                    settings.Username = value;
                    break;
                case "domain":
                    settings.Domain = value;
                    break;
                case "workstation":
                    settings.Workstation = value;
                    break;
                case "password":
                    settings.Password = value;
                    break;
                case "passlm":
                    settings.PassLM = value;
                    break;
                case "passnt":
                    settings.PassNT = value;
                    break;
                case "passntlmv2":
                    settings.PassNTLMv2 = value;
                    break;
                case "auth":
                    settings.Auth = value;
                    break;
                case "flags":
                    settings.Flags = value;
                    break;
                case "listen":
                    if (value.Length > 0) settings.Listen = value;
                    break;
                case "gateway":
                    settings.Gateway = value.Equals("yes", StringComparison.OrdinalIgnoreCase);
                    break;
                case "proxy":
                    if (value.Length > 0 && !value.Equals("127.0.0.1:9", StringComparison.OrdinalIgnoreCase))
                    {
                        proxies.Add(value);
                        settings.UseProxy = true;
                    }
                    break;
                case "noproxy":
                    noProxy.AddRange(value.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries));
                    break;
                case "pac":
                    settings.UsePac = true;
                    settings.PacFile = value;
                    break;
                case "socks5proxy":
                    settings.UseSocks5 = true;
                    settings.Socks5Proxy = value;
                    break;
                case "socks5user":
                    settings.Socks5User = value;
                    break;
                case "allow":
                    if (value.Length > 0)
                    {
                        settings.UseAllow = true;
                        allow.Add(value);
                    }
                    break;
                case "deny":
                    if (value.Length > 0)
                    {
                        settings.UseAllow = true;
                        deny.Add(value);
                    }
                    break;
                case "tunnel":
                    if (value.Length > 0)
                    {
                        settings.UseTunnel = true;
                        tunnels.Add(value);
                    }
                    break;
                case "header":
                    if (value.Length > 0)
                    {
                        settings.UseHeader = true;
                        headers.Add(value);
                    }
                    break;
                case "isascannersize":
                    if (int.TryParse(value, out var size))
                    {
                        settings.IsaScannerSize = size;
                        if (size >= 0) settings.UseIsaScanner = true;
                    }
                    break;
                case "isascanneragent":
                    if (value.Length > 0)
                    {
                        settings.UseIsaScanner = true;
                        agents.Add(value);
                    }
                    break;
                case "sspi":
                    settings.UseSspi = true;
                    settings.SspiType = string.IsNullOrWhiteSpace(value) ? "NTLM" : value;
                    break;
            }
        }

        settings.ProxyList = string.Join("\r\n", proxies);
        settings.NoProxyList = string.Join(", ", noProxy);
        settings.AllowList = string.Join("\r\n", allow);
        settings.DenyList = string.Join("\r\n", deny);
        settings.TunnelList = string.Join("\r\n", tunnels);
        settings.HeaderList = string.Join("\r\n", headers);
        settings.IsaScannerAgentList = string.Join("\r\n", agents);

        return settings;
    }

    private static bool IsBlank(string? value) => string.IsNullOrWhiteSpace(value);
}
